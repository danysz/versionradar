func TestWebhookPlansLocalhostAndPublicURLFlag(t *testing.T) {
	t.Run("webhookPlans returns is_localhost=true and localhost public_url via local test server", func(t *testing.T) {
		t.Setenv("VR_DEV_PASSWORD_AUTH", "1")
		t.Setenv("VR_GOOGLE_CLIENT_ID", "test-client-id")
		t.Setenv("VR_GOOGLE_CLIENT_SECRET", "test-client-secret")

		app, err := tests.NewTestApp()
		if err != nil {
			t.Fatalf("failed to create test app: %v", err)
		}
		t.Cleanup(app.Cleanup)

		cipher, err := core.NewCipher(base64.StdEncoding.EncodeToString([]byte(strings.Repeat("k", 32))))
		if err != nil {
			t.Fatalf("failed to create cipher: %v", err)
		}

		svc := &core.Service{
			App:        app,
			Cipher:     cipher,
			Registry:   core.NewRegistry(server.CommunityProviders()...),
			Sources:    core.NewSourceRegistry(server.CommunitySources()...),
			Strategies: core.NewStrategyRegistry(strategies.All()...),
			Notifiers:  core.NewNotifierRegistry(),
		}
		svc.Bind(app)

		pbRouter, err := apis.NewRouter(app)
		if err != nil {
			t.Fatalf("failed to create router: %v", err)
		}

		var handler http.Handler
		serveEvent := &pbcore.ServeEvent{App: app, Router: pbRouter}
		if err := app.OnServe().Trigger(serveEvent, func(e *pbcore.ServeEvent) error {
			var buildErr error
			handler, buildErr = e.Router.BuildMux()
			return buildErr
		}); err != nil {
			t.Fatalf("OnServe failed: %v", err)
		}

		users, err := app.FindCollectionByNameOrId("users")
		if err != nil {
			t.Fatalf("failed to find users collection: %v", err)
		}
		u := pbcore.NewRecord(users)
		u.SetEmail("webhook-test@example.com")
		u.SetPassword("password123")
		if err := app.Save(u); err != nil {
			t.Fatalf("failed to save user: %v", err)
		}
		token, err := u.NewAuthToken()
		if err != nil {
			t.Fatalf("failed to create auth token: %v", err)
		}

		req := httptest.NewRequest(http.MethodGet, "http://localhost:8080/api/v1/webhooks/plans", nil)
		req.Header.Set("Authorization", token)
		rec := httptest.NewRecorder()
		handler.ServeHTTP(rec, req)

		res := rec.Result()
		defer res.Body.Close()

		if res.StatusCode != http.StatusOK {
			t.Fatalf("expected 200, got %d: %s", res.StatusCode, rec.Body.String())
		}

		var payload struct {
			PublicURL   string `json:"public_url"`
			IsLocalhost bool   `json:"is_localhost"`
		}
		if err := json.NewDecoder(res.Body).Decode(&payload); err != nil {
			t.Fatalf("failed to decode JSON response: %v", err)
		}
		if !payload.IsLocalhost {
			t.Fatalf("expected is_localhost=true, got false (public_url=%q)", payload.PublicURL)
		}
		if !strings.Contains(payload.PublicURL, "localhost") {
			t.Fatalf("expected public_url to contain localhost, got %q", payload.PublicURL)
		}
	})

	t.Run("public-url flag is registered on app.RootCmd and applied on serve", func(t *testing.T) {
		t.Chdir(t.TempDir())
		t.Setenv("VR_ENCRYPTION_KEY", base64.StdEncoding.EncodeToString([]byte(strings.Repeat("k", 32))))
		t.Setenv("VR_DEV_PASSWORD_AUTH", "1")
		t.Setenv("VR_GOOGLE_CLIENT_ID", "test-client-id")
		t.Setenv("VR_GOOGLE_CLIENT_SECRET", "test-client-secret")

		app, svc, err := server.New(server.Options{})
		if err != nil {
			t.Fatalf("server.New failed: %v", err)
		}

		flag := app.RootCmd.PersistentFlags().Lookup("public-url")
		if flag == nil {
			t.Fatal("expected --public-url persistent flag to be registered on app.RootCmd")
		}
		if err := app.RootCmd.PersistentFlags().Set("dir", t.TempDir()); err != nil {
			t.Fatalf("failed to set --dir flag: %v", err)
		}
		if err := app.RootCmd.PersistentFlags().Set("public-url", "https://xyz.trycloudflare.com/"); err != nil {
			t.Fatalf("failed to set --public-url flag: %v", err)
		}
		if err := app.Bootstrap(); err != nil {
			t.Fatalf("app.Bootstrap failed: %v", err)
		}
		t.Cleanup(func() { _ = app.ResetBootstrapState() })

		pbRouter, err := apis.NewRouter(app)
		if err != nil {
			t.Fatalf("failed to create router: %v", err)
		}
		if err := app.OnServe().Trigger(&pbcore.ServeEvent{App: app, Router: pbRouter}, func(e *pbcore.ServeEvent) error {
			return nil
		}); err != nil {
			t.Fatalf("OnServe failed: %v", err)
		}
		if svc.PublicURL != "https://xyz.trycloudflare.com" {
			t.Fatalf("expected svc.PublicURL to be updated from --public-url flag, got %q", svc.PublicURL)
		}
	})
}

func TestAutoGeneratedEncryptionKey(t *testing.T) {
	tempDir := t.TempDir()
	t.Setenv("VR_ENCRYPTION_KEY", "")
	if err := os.Unsetenv("VR_ENCRYPTION_KEY"); err != nil {
		t.Fatalf("failed to unset VR_ENCRYPTION_KEY: %v", err)
	}

	origArgs := os.Args
	os.Args = []string{"versionradar", "--dir=" + tempDir}
	t.Cleanup(func() { os.Args = origArgs })

	app1, svc1, err := server.New(server.Options{})
	if err != nil {
		t.Fatalf("first server.New failed: %v", err)
	}
	if app1.DataDir() != tempDir {
		t.Fatalf("expected app.DataDir()=%q, got %q", tempDir, app1.DataDir())
	}

	keyPath := filepath.Join(tempDir, "encryption.key")
	keyBytes1, err := os.ReadFile(keyPath)
	if err != nil {
		t.Fatalf("failed to read generated encryption.key: %v", err)
	}
	key1 := strings.TrimSpace(string(keyBytes1))
	if len(key1) != 44 {
		t.Fatalf("expected generated key length 44, got %d (%q)", len(key1), key1)
	}

	info, err := os.Stat(keyPath)
	if err != nil {
		t.Fatalf("failed to stat encryption.key: %v", err)
	}
	if perm := info.Mode().Perm(); perm != 0600 {
		t.Fatalf("expected encryption.key mode 0600, got %o", perm)
	}

	encrypted, err := svc1.Cipher.Encrypt("secret-token")
	if err != nil {
		t.Fatalf("svc1.Cipher.Encrypt failed: %v", err)
	}

	_, svc2, err := server.New(server.Options{})
	if err != nil {
		t.Fatalf("second server.New failed: %v", err)
	}

	keyBytes2, err := os.ReadFile(keyPath)
	if err != nil {
		t.Fatalf("failed to re-read encryption.key: %v", err)
	}
	key2 := strings.TrimSpace(string(keyBytes2))
	if key2 != key1 {
		t.Fatalf("expected second server.New to reuse existing key %q, got %q", key1, key2)
	}

	decrypted, err := svc2.Cipher.Decrypt(encrypted)
	if err != nil {
		t.Fatalf("svc2.Cipher.Decrypt failed: %v", err)
	}
	if decrypted != "secret-token" {
		t.Fatalf("expected decrypted value %q, got %q", "secret-token", decrypted)
	}
}
